"""Build a class's files, validate them, and only then call anything printable.

Files are generated in a staging folder and judged there. Any earlier output is
removed first, so a stale print-ready file can't outlive the grades it came from.
Failed files land in NOT_PRINT_READY/ with the phrase in their names too.

Status ladder, lowest first:
    BLOCKED                     an essential check failed
    AWAITING_VISUAL_AUDIT       software checks pass; someone must inspect the rendered pages
    READY_FOR_PHOTOCOPY_PROOF   audited; the printer setup hasn't been proven on paper
    READY_FOR_ORIGINALS         the teacher confirmed a successful physical test
"""
from __future__ import annotations

import shutil
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Optional

import pymupdf

from . import SCHEMA_VERSION, __version__, correction_overlay, decorations, reports, validator
from .common import MM, Issues, PaperGraderError, load_json, save_json, sha256_file
from .decorations import InkMap
from .grading_models import Slot, format_points
from .job import Job
from .pdf_processor import ink_map, page_jpeg

OUTPUT_MARKER = ".papergrader_output"
BLOCKED = "BLOCKED"
AWAITING_AUDIT = "AWAITING_VISUAL_AUDIT"
READY_PROOF = "READY_FOR_PHOTOCOPY_PROOF"
READY_ORIGINALS = "READY_FOR_ORIGINALS"

STATUS_TEXT = {
    BLOCKED: "DO NOT PRINT. An essential check failed. See the errors in the validation report.",
    AWAITING_AUDIT: "DO NOT PRINT YET. Software checks passed. Inspect the rendered pages in proofs/, then record the audit with attest-audit.",
    READY_PROOF: "Print on PHOTOCOPIES ONLY. Physical alignment on this printer isn't confirmed yet.",
    READY_ORIGINALS: "Ready for the original papers. The teacher confirmed a physical calibration test for this printer profile.",
}


def output_names(class_id: str) -> dict[str, str]:
    return {
        "corrections": f"{class_id}_corrections_NORMAL_ORDER.pdf",
        "preview": f"{class_id}_correction_PREVIEW_DO_NOT_PRINT.pdf",
        "results_csv": f"{class_id}_student_results.csv",
        "details_csv": f"{class_id}_answer_details.csv",
        "results_xlsx": f"{class_id}_student_results.xlsx",
        "summary": f"{class_id}_grading_summary.pdf",
        "roster": f"{class_id}_student_score_roster.pdf",
        "answer_key": f"{class_id}_answer_key_list.pdf",
        "print_mapping": f"{class_id}_print_order_mapping.csv",
        "decoration_audit": f"{class_id}_decoration_audit.json",
        "overlay_plan": f"{class_id}_overlay_plan.json",
    }


def _clear_output(folder: Path) -> None:
    """Remove earlier generated files. Only touches a folder this code created and marked."""
    if folder.exists():
        if not (folder / OUTPUT_MARKER).is_file():
            raise PaperGraderError(f"{folder} exists but isn't a PaperGrader output folder, so it won't be deleted.")
        shutil.rmtree(folder)
    folder.mkdir(parents=True)
    (folder / OUTPUT_MARKER).write_text("generated by PaperGrader; safe to rebuild\n", encoding="utf-8")


def _slot_ink(job: Job, cache: dict[int, InkMap]):
    def provider(slot: Slot) -> InkMap:
        if slot.slot not in cache:
            cache[slot.slot] = ink_map(job.source_path(slot.source_pdf), slot.source_page, slot.scan_rotation) if slot.kind == "scan" else InkMap.empty()
        return cache[slot.slot]

    return provider


def _check_offsets(plans: list[dict], offset_mm: tuple[float, float], issues: Issues) -> None:
    """A calibration offset must not push anything off the printable page."""
    ox, oy = offset_mm[0] * MM, offset_mm[1] * MM
    for plan in plans:
        rects = correction_overlay.planned_rects(plan)
        for group in rects.values():
            for box in group:
                if box[0] + ox < 0 or box[1] + oy < 0 or box[2] + ox > plan["page_width_pt"] or box[3] + oy > plan["page_height_pt"]:
                    issues.error("offset_pushes_art_off_page", f"With offset ({offset_mm[0]:+g}, {offset_mm[1]:+g}) mm, part of the overlay falls off the page.", f"slot {plan['slot']}")
                    return


def _write_proofs(corrections: Path, preview: Path, folder: Path, slots: list[int]) -> list[str]:
    """Render pages to PNG so a person or model can inspect the finished output."""
    folder.mkdir(parents=True, exist_ok=True)
    written: list[str] = []
    with pymupdf.open(corrections) as overlay, pymupdf.open(preview) as composed:
        for slot in slots:
            overlay_file = folder / f"slot-{slot:04d}_overlay.png"
            preview_file = folder / f"slot-{slot:04d}_preview.png"
            # Rendered on white, since that is how transparent overlay pages look on paper.
            overlay[slot - 1].get_pixmap(dpi=110, alpha=False).save(overlay_file)
            composed[slot - 1].get_pixmap(dpi=110, alpha=False).save(preview_file)
            written += [overlay_file.name, preview_file.name]
    return written


def build_class(job: Job, class_id: str, _skip_embroidery: bool = False, _skip_stamp: bool = False) -> dict[str, Any]:
    """Generate and validate every output for one class. Returns the validation report.

    The underscore flags exist only so tests can prove that the validator catches
    missing artwork. They produce a blocked result, never a usable shortcut.
    """
    output = job.output_dir(class_id)
    _clear_output(output)
    bundle = validator.validate_inputs(job, class_id)
    issues = bundle.issues
    names = output_names(class_id)
    if not issues.ok or not (bundle.test and bundle.page_map and bundle.grading):
        return _finish(job, class_id, bundle, issues, outputs_checked=False, plans=[], stage=None)

    test, page_map, grading, outcomes = bundle.test, bundle.page_map, bundle.grading, bundle.outcomes
    grading_hash_before = sha256_file(job.grading_path(class_id))
    offset = (float(bundle.profile["offset_mm"]["x"]), float(bundle.profile["offset_mm"]["y"]))
    margin = float(bundle.profile["safe_margin_mm"])
    stage = output / ".staging"
    stage.mkdir()

    cache: dict[int, InkMap] = {}
    try:
        plans = correction_overlay.plan_class(test, page_map, grading, outcomes, _slot_ink(job, cache), margin, issues)
        validator.validate_plans(plans, test, page_map, outcomes, issues)
        _check_offsets(plans, offset, issues)

        title = f"{page_map.class_label} corrections, normal order"
        corrections = correction_overlay.build_correction_pdf(plans, offset, title, _skip_embroidery, _skip_stamp)
        corrections.save(stage / names["corrections"], garbage=4, deflate=True)
        corrections.close()

        slots_by_number = {s.slot: s for s in page_map.slots}

        def slot_image(number: int) -> Optional[bytes]:
            slot = slots_by_number[number]
            return page_jpeg(job.source_path(slot.source_pdf), slot.source_page) if slot.kind == "scan" else None

        preview = correction_overlay.build_preview_pdf(plans, slot_image, f"{page_map.class_label} preview: do not print on originals")
        preview.save(stage / names["preview"], garbage=4, deflate=True)
        preview.close()
    except PaperGraderError as exc:
        issues.error("art_asset_missing", str(exc), "decorations")
        return _finish(job, class_id, bundle, issues, outputs_checked=False, plans=[], stage=stage)

    warnings = [f"{i.where}: {i.message}" if i.where else i.message for i in issues.warnings]
    reports.build_roster(stage / names["roster"], test, page_map, grading, outcomes)
    reports.build_summary(stage / names["summary"], test, page_map, grading, outcomes, warnings)
    reports.build_answer_key(stage / names["answer_key"], test, page_map.class_label)
    headers, rows = reports.results_rows(test, page_map, grading, outcomes)
    detail_headers, detail_rows = reports.answer_detail_rows(test, grading)
    reports.write_csv(stage / names["results_csv"], headers, rows)
    reports.write_csv(stage / names["details_csv"], detail_headers, detail_rows)
    map_headers, map_rows = reports.print_mapping_rows(page_map, grading)
    reports.write_csv(stage / names["print_mapping"], map_headers, map_rows)
    xlsx = reports.write_xlsx(stage / names["results_xlsx"], [("Students", headers, rows), ("Answers", detail_headers, detail_rows), ("Print order", map_headers, map_rows)])
    if xlsx is None:
        issues.warning("xlsx_unavailable", "openpyxl isn't installed in this runtime, so only CSV results were produced.", "results_xlsx")

    # Judge the real files.
    validator.validate_correction_pdf(stage / names["corrections"], plans, offset, issues)
    validator.validate_preview_pdf(stage / names["preview"], plans, issues)
    report_paths = {key: stage / names[key] for key in ("roster", "summary", "answer_key", "results_csv", "details_csv", "print_mapping", "corrections", "preview")}
    validator.validate_reports(report_paths, page_map, grading, test, outcomes, issues)
    if sha256_file(job.grading_path(class_id)) != grading_hash_before:
        issues.error("grading_changed_during_build", "grading.json changed while the files were being built.", "grading")

    award_slots = [p["slot"] for p in plans if p["stamp"] or p["embroidery"]]
    proof_slots = sorted(set(award_slots) | {plans[0]["slot"], plans[-1]["slot"]})
    _write_proofs(stage / names["corrections"], stage / names["preview"], stage / "proofs", proof_slots)
    audit = {
        "note": "Software checks only. Each listed page still needs inspection by eye: art must not cover writing, and marks must sit on the right answers.",
        "students": [
            {
                "student_order": o.student_order,
                "score": format_points(o.total) if o.resolved else None,
                "award": o.award,
                "slot": next((p["slot"] for p in plans if p["student_order"] == o.student_order and (p["stamp"] or p["score"])), None),
                "stamp_asset": next((p["stamp"]["asset"] for p in plans if p["student_order"] == o.student_order and p["stamp"]), None),
                "embroidery_motifs": next((p["embroidery"]["kept"] for p in plans if p["student_order"] == o.student_order and p["embroidery"]), 0),
            }
            for o in sorted(outcomes.values(), key=lambda o: o.student_order)
        ],
        "slots_requiring_inspection": award_slots,
        "proof_slots": proof_slots,
    }
    save_json(stage / names["decoration_audit"], audit)
    save_json(stage / names["overlay_plan"], {"schema_version": SCHEMA_VERSION, "class_id": class_id, "printer_offset_mm": list(offset), "plans": plans})
    return _finish(job, class_id, bundle, issues, outputs_checked=True, plans=plans, stage=stage, award_slots=award_slots)


def _finish(job: Job, class_id: str, bundle: validator.InputBundle, issues: Issues, outputs_checked: bool, plans: list[dict], stage: Optional[Path], award_slots: Optional[list[int]] = None) -> dict[str, Any]:
    output = job.output_dir(class_id)
    blocked = not issues.ok
    files: dict[str, str] = {}
    if stage and stage.exists():
        destination = output / "NOT_PRINT_READY" if blocked else output
        destination.mkdir(exist_ok=True)
        for item in sorted(stage.iterdir()):
            name = f"NOT_PRINT_READY_{item.name}" if blocked else item.name
            shutil.move(str(item), destination / name)
        stage.rmdir()
        for path in sorted(destination.rglob("*")):
            if path.is_file() and path.name != OUTPUT_MARKER:
                files[str(path.relative_to(output)).replace("\\", "/")] = sha256_file(path)

    grading_path = job.grading_path(class_id)
    calibrated = bundle.profile.get("calibration", {}).get("physically_verified") is True
    outcomes = bundle.outcomes
    report: dict[str, Any] = {
        "schema_version": SCHEMA_VERSION,
        "papergrader_version": __version__,
        "class_id": class_id,
        "status": BLOCKED if blocked else AWAITING_AUDIT,
        "status_meaning": "",
        "built_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "synthetic_data": bool(bundle.grading and bundle.grading.grader_type == "synthetic_fixture"),
        "checks": validator.checks_summary(issues, outputs_checked),
        "counts": {
            "printable_pages": len(plans),
            "students": len(outcomes),
            "confirmed": sum(1 for o in outcomes.values() if o.resolved),
            "pending": sum(1 for o in outcomes.values() if not o.resolved),
            "praise_awards": sum(1 for o in outcomes.values() if o.award == "praise"),
            "perfect_awards": sum(1 for o in outcomes.values() if o.award == "perfect"),
        },
        "physical_calibration_verified": calibrated,
        "visual_audit": {"required_slots": award_slots or [], "passed": False, "attested_at": None},
        "inputs": {
            "grading_sha256": sha256_file(grading_path) if grading_path.is_file() else None,
            "rubric_hash": bundle.test.rubric_hash() if bundle.test else None,
        },
        "outputs": files,
        "limits": [
            "These checks measure files and records. They can't confirm that a handwriting reading is correct.",
            "Physical alignment is proven only by a real print on photocopies.",
        ],
        **issues.to_json(),
    }
    report["status_meaning"] = STATUS_TEXT[report["status"]]
    _write_report(job, class_id, report)
    return report


def _write_report(job: Job, class_id: str, report: dict[str, Any]) -> None:
    output = job.output_dir(class_id)
    save_json(output / f"{class_id}_validation_report.json", report)
    lines = [f"{class_id}: {report['status']}", report["status_meaning"], ""]
    if report["errors"]:
        lines.append(f"{len(report['errors'])} error(s):")
        lines += [f"  [{e['code']}] {e['where']}: {e['message']}" for e in report["errors"]]
    if report["warnings"]:
        lines.append(f"{len(report['warnings'])} warning(s):")
        lines += [f"  [{w['code']}] {w['where']}: {w['message']}" for w in report["warnings"]]
    (output / "PRINT_STATUS.txt").write_text("\n".join(lines) + "\n", encoding="utf-8")


def load_report(job: Job, class_id: str) -> dict[str, Any]:
    return load_json(job.output_dir(class_id) / f"{class_id}_validation_report.json")


def attest_audit(job: Job, class_id: str, inspected_slots: list[int], statement: str) -> dict[str, Any]:
    """Record that someone viewed the finished pages. Every decorated page must be covered."""
    report = load_report(job, class_id)
    if report["status"] == BLOCKED:
        raise PaperGraderError("This build is blocked. Fix its errors and rebuild before auditing.")
    if not statement.strip():
        raise PaperGraderError("Describe what was inspected and what was seen.")
    missing = sorted(set(report["visual_audit"]["required_slots"]) - set(inspected_slots))
    if missing:
        raise PaperGraderError(f"Every decorated page must be inspected. Not yet covered: slots {missing}.")
    if not inspected_slots:
        raise PaperGraderError("Inspect at least one finished page against its scan.")
    _assert_outputs_unchanged(job, class_id, report)
    report["visual_audit"] = {
        **report["visual_audit"], "passed": True, "inspected_slots": sorted(set(inspected_slots)), "statement": statement.strip(),
        "attested_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
    }
    report["status"] = READY_ORIGINALS if job.load_profile()["calibration"]["physically_verified"] else READY_PROOF
    report["physical_calibration_verified"] = job.load_profile()["calibration"]["physically_verified"] is True
    report["status_meaning"] = STATUS_TEXT[report["status"]]
    _write_report(job, class_id, report)
    return report


def _assert_outputs_unchanged(job: Job, class_id: str, report: dict[str, Any]) -> None:
    output = job.output_dir(class_id)
    for name, digest in report["outputs"].items():
        path = output / name
        if not path.is_file() or sha256_file(path) != digest:
            raise PaperGraderError(f"{name} changed or disappeared after the build. Rebuild the class.")
    grading = job.grading_path(class_id)
    if sha256_file(grading) != report["inputs"]["grading_sha256"]:
        raise PaperGraderError("grading.json changed after the build. Rebuild the class.")


def current_status(job: Job, class_id: str) -> dict[str, Any]:
    """Re-check the finished files against their recorded hashes and the current printer state."""
    report = load_report(job, class_id)
    try:
        _assert_outputs_unchanged(job, class_id, report)
    except PaperGraderError as exc:
        return {**report, "status": BLOCKED, "status_meaning": f"DO NOT PRINT. {exc}"}
    if report["status"] in (READY_PROOF, READY_ORIGINALS):
        verified = job.load_profile()["calibration"]["physically_verified"] is True
        status = READY_ORIGINALS if verified else READY_PROOF
        return {**report, "status": status, "status_meaning": STATUS_TEXT[status], "physical_calibration_verified": verified}
    return report
