const LANGUAGE_KEY = 'papergrader-language-v2';
let language =
  localStorage.getItem(LANGUAGE_KEY) || (navigator.language?.toLowerCase().startsWith('ja') ? 'ja' : 'en');
if (!dictionaries[language]) language = 'en';

export function getLanguage() {
  return language;
}

export function setLanguage(next) {
  language = dictionaries[next] ? next : 'en';
  localStorage.setItem(LANGUAGE_KEY, language);
  document.documentElement.lang = language;
}

export function t(key, vars = {}) {
  const value = dictionaries[language][key] ?? dictionaries.en[key] ?? key;
  return Object.entries(vars).reduce(
    (text, [name, replacement]) => text.replaceAll(`{${name}}`, replacement),
    value,
  );
}

export function applyI18n(root = document) {
  document.documentElement.lang = language;
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.title = t(el.dataset.i18nTitle);
  });
  root.querySelectorAll('[data-i18n-aria]').forEach((el) => {
    el.setAttribute('aria-label', t(el.dataset.i18nAria));
  });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
}
